def run_scaled_experiment(features, scaler_class, alpha, iterations):
    X_train = df[features].values[train_idx].astype(float)
    X_val   = df[features].values[val_idx].astype(float)

    scaler = scaler_class().fit(X_train)
    Xs_train = scaler.transform(X_train)
    Xs_val   = scaler.transform(X_val)

    Xb_train = add_bias(Xs_train)
    Xb_val   = add_bias(Xs_val)

    theta, train_losses, val_losses = train_gradient_descent(
        Xb_train, y_train, Xb_val, y_val, alpha, iterations)
    return theta, train_losses, val_losses

