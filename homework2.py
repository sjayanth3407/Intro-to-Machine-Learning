def add_bias(X):
    return np.hstack((np.ones((X.shape[0], 1)), X))


def compute_loss(X, y, theta):
    m = len(y)
    errors = X.dot(theta) - y
    return (1 / m) * np.sum(np.square(errors))


def train_gradient_descent(X_train, y_train, X_val, y_val, alpha, iterations, reg_lambda=0.0):
    m = len(y_train)
    theta = np.zeros((X_train.shape[1], 1))
    train_losses = []
    val_losses = []

    for i in range(iterations):
        errors = X_train.dot(theta) - y_train
        gradients = (2 / m) * X_train.T.dot(errors)

        if reg_lambda > 0:
            theta_penalized = theta.copy()
            theta_penalized[0, 0] = 0
            gradients = gradients + (2 * reg_lambda / m) * theta_penalized

        theta = theta - alpha * gradients

        train_losses.append(compute_loss(X_train, y_train, theta))
        val_losses.append(compute_loss(X_val, y_val, theta))

    return theta, train_losses, val_losses


def plot_train_val_loss(train_losses, val_losses, title, yscale='linear'):
    plt.figure(figsize=(8, 5))
    plt.plot(train_losses, label='Training Loss')
    plt.plot(val_losses, label='Validation Loss')
    plt.xlabel('Iteration')
    plt.ylabel('Mean Squared Error')
    plt.yscale(yscale)
    plt.title(title)
    plt.legend()
    plt.grid(True)
    plt.show()

